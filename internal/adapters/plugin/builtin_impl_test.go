func TestBuiltinCanceledBeforeExecution(t *testing.T) {
	t.Parallel()

	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	executor := NewBuiltinPluginExecutor(logger.NewNop())

	output, err := executor.runWasmPlugin(ctx, "memory", strings.NewReader(""))

	require.ErrorIs(t, err, context.Canceled)
	assert.Nil(t, output)
}

func TestBuiltinUniversalOutputCompatibility(t *testing.T) {
	t.Parallel()

	request, err := proto.Marshal(&pluginpb.CodeGeneratorRequest{
		FileToGenerate: []string{"example.proto"},
		ProtoFile: []*descriptorpb.FileDescriptorProto{{
			Name: proto.String("example.proto"), Package: proto.String("example"), Syntax: proto.String("proto3"),
			MessageType: []*descriptorpb.DescriptorProto{{
				Name: proto.String("Greeting"),
				Field: []*descriptorpb.FieldDescriptorProto{{
					Name: proto.String("text"), Number: proto.Int32(1),
					Label: descriptorpb.FieldDescriptorProto_LABEL_OPTIONAL.Enum(),
					Type:  descriptorpb.FieldDescriptorProto_TYPE_STRING.Enum(),
				}},
			}},
			Service: []*descriptorpb.ServiceDescriptorProto{{
				Name: proto.String("Greeter"),
				Method: []*descriptorpb.MethodDescriptorProto{{
					Name: proto.String("Hello"), InputType: proto.String(".example.Greeting"), OutputType: proto.String(".example.Greeting"),
				}},
			}},
		}},
	})
	require.NoError(t, err)
	ctx, run := EnsureBuiltinRun(t.Context())
	t.Cleanup(func() { assert.NoError(t, run.Close(context.Background())) })
	for _, name := range []string{"python", "grpc_python"} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			want := builtinDirectOutput(t, name, request)
			executor := NewBuiltinPluginExecutor(logger.NewNop())

			got, err := executor.runWasmPlugin(ctx, name, bytes.NewReader(request))

			require.NoError(t, err)
			assert.Equal(t, want, got, "compiled execution must preserve the original runtime's generated bytes")
			var response pluginpb.CodeGeneratorResponse
			require.NoError(t, proto.Unmarshal(got, &response))
			require.Empty(t, response.GetError())
			require.NotEmpty(t, response.File)
		})
	}
}

func TestBuiltinStandaloneModule(t *testing.T) {
	t.Parallel()

	for range 2 {
		output, err := runBuiltinModule(t.Context(), builtinEchoModule(t), []string{"echo"}, strings.NewReader("standalone"))
		require.NoError(t, err)
		assert.Equal(t, "standalone", string(output))
	}
}

// builtinDirectOutput reproduces the previous per-invocation compilation path.
// It intentionally has no shared cache or context-termination instrumentation.
func builtinDirectOutput(t *testing.T, pluginName string, request []byte) []byte {
	t.Helper()
	ctx := experimental.WithMemoryAllocator(t.Context(), allocator.NewNonMoving())
	runtime := wazero.NewRuntimeWithConfig(ctx, wazero.NewRuntimeConfig().WithCoreFeatures(api.CoreFeaturesV2|experimental.CoreFeaturesThreads))
	defer func() { assert.NoError(t, runtime.Close(context.WithoutCancel(ctx))) }()
	_, err := wasi_snapshot_preview1.Instantiate(ctx, runtime)
	require.NoError(t, err)
	_, err = runtime.InstantiateWithConfig(ctx, wasmMemory, wazero.NewModuleConfig().WithName("env"))
	require.NoError(t, err)
	var stdout, stderr bytes.Buffer
	_, err = runtime.InstantiateWithConfig(ctx, protocGenUniversal, wazero.NewModuleConfig().
		WithSysNanosleep().WithSysNanotime().WithSysWalltime().
		WithStdin(bytes.NewReader(request)).WithStdout(&stdout).WithStderr(&stderr).
		WithRandSource(rand.Reader).WithArgs("protoc-gen-universal", pluginName))
	require.NoError(t, err, stderr.String())
	return stdout.Bytes()
}
